<#
.SYNOPSIS
Retrieves a list of files to exclude based on a specified exclusions file.

.DESCRIPTION
The GetExclusions function reads a JSON file containing a list of exclusions and returns the list of files to exclude. If the exclusions file is not found, it returns an empty list and logs a message.

.PARAMETER ExclusionsFile
The path to the exclusions file. Defaults to 'exclusions.json' in the script's root directory.

.EXAMPLE    
GetExclusions -ExclusionsFile "C:\\path\\to\\exclusions.json"
Retrieves the list of exclusions from the specified file.

.NOTES
Version: 1.0.0
Author: Zuhair Mahmoud
Date: April 5, 2025
#>
function GetExclusions()
{
    [CmdletBinding()]
    param(
        [string]$ExclusionsFile = "$PSScriptRoot\exclusions.json"
    )
    Write-Verbose "ExclusionsFile: $ExclusionsFile"
    if (Test-Path -Path $ExclusionsFile)
    {
        $filesToExclude = (Get-Content -Path $ExclusionsFile | ConvertFrom-Json).exclusions
        Write-Verbose "Reading $($filesToExclude.Count) exclusions from $($ExclusionsFile)..."
        if ($filesToExclude.Count -gt 0)
        {
            Write-Verbose 'Files to exclude:'
            $filesToExclude | ForEach-Object { Write-Verbose $_ }
        }
        else 
        {
            Write-Host "No exclusions found in $($ExclusionsFile)"
        }
    }
    else
    {
        Write-Host "Cannot find the exclusion file $($ExclusionsFile)."
        $filesToExclude = ''
    }
    return $filesToExclude
}


