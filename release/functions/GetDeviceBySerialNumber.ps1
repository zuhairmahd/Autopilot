function GetDeviceBySerialNumber () {
    [CmdletBinding()]
    param
    (
        [Parameter(Mandatory = $true)]
        $serialNumber
    )
    Write-Verbose "Searching for device with serial number $serialNumber"
    $uri = "https://graph.microsoft.com/beta/deviceManagement/managedDevices"
    $devices = Invoke-MgGraphRequest -Uri $uri -Method Get -OutputType PSObject
    $devices = $devices.value
    foreach ($device in $devices) {
        Write-Verbose "Checking device with serial number $($device.serialNumber)"
        if ($device.serialNumber -eq $serialNumber) {
            Write-Verbose "Device found with serial number $serialNumber"
            $deviceToReturn = $device
            break
        }
        else {
            Write-Verbose "Device not found with serial number $serialNumber"
        }
    }
    if ($deviceToReturn) {
        Write-Verbose "Device found with serial number $serialNumber"
        return $deviceToReturn
    }
    else {
        Write-Verbose "Device not found with serial number $serialNumber"
        return $null    
    }
}

